def _format_large_number(value: float) -> str:
    """Format a number into human-readable large number notation."""
    if not value:
        return "N/A"
    abs_val = abs(value)
    sign = "-" if value < 0 else ""
    if abs_val >= 1e12:
        return f"{sign}${abs_val / 1e12:.2f}T"
    elif abs_val >= 1e9:
        return f"{sign}${abs_val / 1e9:.2f}B"
    elif abs_val >= 1e6:
        return f"{sign}${abs_val / 1e6:.2f}M"
    elif abs_val >= 1e3:
        return f"{sign}${abs_val / 1e3:.2f}K"
    else:
        return f"{sign}${abs_val:.2f}"


def _rate_metric(value: float, cheap: float, expensive: float) -> str:
    """Rate a valuation metric as Cheap/Fair/Expensive."""
    if not value:
        return ""
    if value <= cheap:
        return "🟢 Cheap"
    elif value <= expensive:
        return "🟡 Fair"
    else:
        return "🔴 Expensive"
