from finra.agent.state import MarketData


def format_metrics_table(market: MarketData) -> str:
    """Format market metrics into a Markdown table."""
    rows = [
        ("Current Price", f"${market.current_price:.2f}", ""),
        ("Price Change", f"{market.price_change_pct:+.2f}%", ""),
        ("Market Cap", _format_large_number(market.market_cap), ""),
        ("", "", ""),
        ("P/E Ratio", f"{market.pe_ratio:.1f}", _rate_metric(market.pe_ratio, 15, 25)),
        ("P/S Ratio", f"{market.ps_ratio:.2f}", _rate_metric(market.ps_ratio, 3, 8)),
        ("P/B Ratio", f"{market.pb_ratio:.2f}", _rate_metric(market.pb_ratio, 1, 3)),
        ("Dividend Yield", f"{market.dividend_yield * 100:.2f}%" if market.dividend_yield else "N/A", ""),
        ("", "", ""),
        ("Revenue", _format_large_number(market.revenue), ""),
        ("Revenue Growth", f"{market.revenue_growth:+.1f}%", ""),
        ("Net Income", _format_large_number(market.net_income), ""),
        ("Free Cash Flow", _format_large_number(market.free_cash_flow), ""),
        ("", "", ""),
        ("Gross Margin", f"{market.gross_margin * 100:.1f}%" if market.gross_margin else "N/A", ""),
        ("Operating Margin", f"{market.operating_margin * 100:.1f}%" if market.operating_margin else "N/A", ""),
        ("Net Margin", f"{market.net_margin * 100:.1f}%" if market.net_margin else "N/A", ""),
        ("ROE", f"{market.roe * 100:.1f}%" if market.roe else "N/A", ""),
        ("Debt/Equity", f"{market.debt_to_equity:.1f}" if market.debt_to_equity else "N/A", ""),
    ]

    lines = ["| Metric | Value | |", "|--------|-------|-|"]
    for metric, value, rating in rows:
        if not metric and not value:
            lines.append("| | | |")
        else:
            lines.append(f"| {metric} | {value} | {rating} |")

    return "\n".join(lines)


